import importlib.util
from pathlib import Path
import subprocess
import sys
import unittest

SCRIPT = Path(__file__).resolve().parents[1] / "scripts" / "inspect_text.py"
spec = importlib.util.spec_from_file_location("signal_inspect", SCRIPT)
inspector = importlib.util.module_from_spec(spec)
spec.loader.exec_module(inspector)

class TestInspector(unittest.TestCase):
    def test_clean_text_is_not_authorship_claim(self):
        report = inspector.scan_text("A clear statement with an actual point.")
        self.assertEqual(report["total_findings"], 0)
        self.assertIn("NOT an AI-authorship classifier", " ".join(report["limitations"]))

    def test_zero_width_character_line_and_column(self):
        report = inspector.scan_text("One line\nhe\u200bllo", include_style=False)
        finding = report["examples_by_category"]["zero-width"][0]
        self.assertEqual((finding["line"], finding["column"], finding["codepoint"]), (2, 3, "U+200B"))

    def test_emoji_zwj_is_not_high_confidence_origin(self):
        report = inspector.scan_text("👩\u200d💻", include_style=False)
        self.assertEqual(report["totals_by_category"]["zero-width"], 1)
        self.assertEqual(report["examples_by_category"]["zero-width"][0]["severity"], "review")

    def test_bidi_controls_and_unicode_tag(self):
        report = inspector.scan_text("a\u202eb\U000E0061", include_style=False)
        self.assertEqual(report["totals_by_category"]["bidi-control"], 1)
        self.assertEqual(report["totals_by_category"]["unicode-tag"], 1)

    def test_bom_is_reported_but_neutral(self):
        report = inspector.scan_text("\ufeffhello", include_style=False)
        self.assertIn("common encoding marker", report["examples_by_category"]["bom-or-zero-width"][0]["note"])

    def test_mixed_script_word(self):
        report = inspector.scan_text("pаypal", include_style=False)  # Cyrillic a, Latin surrounding
        self.assertEqual(report["totals_by_category"]["mixed-script-word"], 1)

    def test_no_false_alarm_on_greek_word_alone(self):
        report = inspector.scan_text("κόσμος", include_style=False)
        self.assertNotIn("mixed-script-word", report["totals_by_category"])

    def test_html_comment_preserved(self):
        report = inspector.scan_text("before <!-- generated by someone --> after", include_style=False)
        self.assertEqual(report["totals_by_category"]["html-comment"], 1)

    def test_frontmatter_metadata(self):
        report = inspector.scan_text("---\nmodel_id: x\ntitle: Example\n---\nBody", include_style=False)
        self.assertEqual(report["totals_by_category"]["frontmatter-provenance-field"], 1)

    def test_style_suggestion_is_not_watermark(self):
        report = inspector.scan_text("In today's rapidly evolving landscape, we can unlock success.")
        self.assertIn("style:generic-era-opening", report["totals_by_category"])
        self.assertIn("style:hype-vocabulary", report["totals_by_category"])
        self.assertIn("NOT a statistical", " ".join(report["limitations"]))

    def test_cli_json_stdin(self):
        process = subprocess.run([sys.executable, str(SCRIPT), "--stdin", "--format", "json"],
                                 input="A\u200bB", encoding="utf-8", capture_output=True, check=True)
        self.assertIn('"U+200B"', process.stdout)
        self.assertEqual(process.stderr, "")

if __name__ == "__main__":
    unittest.main()
